MODEL_IDENTIFIER::MODEL_IDENTIFIER(std::shared_ptr<LoggerBase> _logger, std::string _location)
    : SystemBaseWithSolvers(_logger, _location)
{
    author      = "Andreas R.G. Sitorus, Etienne Purcell";
    description = "Ship's Rudder C++ FMU Implementation";
    version     = MODEL_VERSION;
    name        = MODELNAME;
    identifier  = MODEL_IDENTIFIER_STR;
    guid        = fmuGUID;

    // No built-in solver: do_step() does the work
    solverType = "None";
    printInfo  = false;

    // Registration
    RegisterReal(rudder_angle_to_sway_force_coefficient, "rudder_angle_to_sway_force_coefficient", 0.0);
    RegisterReal(rudder_angle_to_yaw_force_coefficient,  "rudder_angle_to_yaw_force_coefficient",  0.0);
    RegisterReal(max_rudder_angle_negative_deg,          "max_rudder_angle_negative_deg",          -30.0);
    RegisterReal(max_rudder_angle_positive_deg,          "max_rudder_angle_positive_deg",          30.0);

    RegisterInput(rudder_angle_deg, "rudder_angle_deg", 0.0);
    RegisterInput(yaw_angle_rad,    "yaw_angle_rad",    0.0);
    RegisterInput(forward_speed,    "forward_speed",    0.0);
    RegisterInput(current_speed,    "current_speed",    0.0);
    RegisterInput(current_dir_rad,  "current_dir_rad",  0.0);

    RegisterOutput(rudder_force_v, "rudder_force_v", 0.0);
    RegisterOutput(rudder_force_r, "rudder_force_r", 0.0);
}

static double sat(double val, double low, double hi)
{
    return std::max(low, std::min(val, hi));
}

// Same as Python math.radians
static double radians(double deg)
{
    return deg * (std::numbers::pi / 180.0);
}

static double rotation_inv_first_component(double yaw_angle_rad, const double vel_ned[3])
{
    // u_current = (R^{-1} * vel)[0]
    // For planar rotation, R^{-1} is rotation by -yaw
    double cy = std::cos(yaw_angle_rad);
    double sy = std::sin(yaw_angle_rad);
    // R^{-1} = [[cy, sy],[-sy, cy]] for 2D
    double u_current = cy * vel_ned[0] + sy * vel_ned[1];
    return u_current;
}

// Takes in the rudder angle and returns the force in sway and yaw generated by the rudder.
void MODEL_IDENTIFIER::get_rudder_force(double rudder_angle_deg, double yaw_angle_rad, double forward_speed,
                                        const double vel_current_ned[3], double& v_force, double& r_force)
{
    double delta_rad = radians(rudder_angle_deg);
    double u_current = rotation_inv_first_component(yaw_angle_rad, vel_current_ned);

    double rel_u = (forward_speed - u_current);
    v_force = -rudder_angle_to_sway_force_coefficient * delta_rad * rel_u;
    r_force = -rudder_angle_to_yaw_force_coefficient  * delta_rad * rel_u;
}

void MODEL_IDENTIFIER::do_step(double current_time, double step_size)
{
    try
    {
        // Inputs
        double yaw     = yaw_angle_rad;
        double rud_deg = rudder_angle_deg;
        double u       = forward_speed;
        double cs      = current_speed;
        double cd      = current_dir_rad;

        // Saturate in DEGREES
        rud_deg = sat(rud_deg, max_rudder_angle_negative_deg, max_rudder_angle_positive_deg);

        double vel_current[3] = {cs * std::cos(cd), cs * std::sin(cd), 0.0};

        get_rudder_force(rud_deg, yaw, u, vel_current, rudder_force_v, rudder_force_r);
    }
    catch (const std::exception& e)
    {
        // IMPORTANT: do not crash host
        std::cout << "[Rudder] ERROR t=" << current_time << " dt=" << step_size << ": " << e.what() << std::endl;

        rudder_force_v = 0.0;
        rudder_force_r = 0.0;
    }
}

void MODEL_IDENTIFIER::DoStep(const double globalTime)
{
    do_step(time, globalTime - time);
    SystemBaseWithSolvers::DoStep(globalTime);
}
